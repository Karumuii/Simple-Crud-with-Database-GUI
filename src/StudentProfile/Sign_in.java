    public void reg() {
        Login l = new Login(); //Not Included in 
        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
            con = (Connection) DriverManager.getConnection("jdbc:mysql://127.0.0.1:3306/student?allowPublicKeyRetrieval=true&useSSL=false", "root", "root");

            ps = con.prepareStatement("INSERT INTO Login (UserId, username, password) values (?,?,?)");

            ps.setString(1, uid.getText());
            ps.setString(2, user.getText());
            ps.setString(3, pass.getText());

            ps.executeUpdate();

            JOptionPane.showMessageDialog(rootPane, "Registered Successfully");
            this.dispose();       //Not Included in
            l.setVisible(true); //Not Included in

            uid.setText("");
            user.setText("");
            pass.setText("");

        } catch (ClassNotFoundException ex) {
            System.getLogger(Sign_in.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        } catch (SQLException ex) {
            System.getLogger(Sign_in.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }

    public void autoincrementid() {
        try {
            d.rs = d.stat.executeQuery("SELECT UserId from Login ORDER BY UserId DESC LIMIT 1");

            if (d.rs.next()) {
                int id = d.rs.getInt(1);
                int n = id + 1;
                uid.setText(Integer.toString(n));
            }
        } catch (SQLException ex) {
            System.getLogger(Sign_in.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }

