    private void log() {
        String u = user.getText();
        String pws = pass.getText();

        try {
            d.ps = d.con.prepareStatement("SELECT username, password FROM login WHERE username = ?");
            d.ps.setString(1, u);

            d.rs = d.ps.executeQuery();

            if (u.isEmpty() || pws.isEmpty()) {
                JOptionPane.showMessageDialog(rootPane, "Username and password cannot be empty!!");
                return;
            }
            if (d.rs.next()){
                String pw = d.rs.getString("password");
                String un = d.rs.getString("username");
                
                if (un.equals(u) && pw.equals(pws)){
                    JOptionPane.showMessageDialog(rootPane, "Login Successfully!");
                    
                    Student_Information s = new Student_Information();
                    this.dispose();
                    s.setVisible(true);
                } else {
                    JOptionPane.showMessageDialog(rootPane, "Invalid username or password");
                }

            }
            else {
                JOptionPane.showMessageDialog(rootPane, "User not found!");
                
            }
        } catch (SQLException ex) {
            System.getLogger(Login.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }

