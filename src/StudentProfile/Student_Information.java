    public void save() {
        try {
            Class.forName("com.mysql.cj.jdbc.Driver");                           // Schema Name              
            con = (Connection) DriverManager.getConnection("jdbc:mysql://127.0.0.1:3306/student?allowPublicKeyRetrieval=true&useSSL=false", "root", "root");
            //                                            Table Name           Row Variables/values                 5 Question mark because the column and Column has 5 variables
            ps = con.prepareStatement("INSERT INTO student_information (UserId, firstname, middlename, lastname, age) values (?,?,?,?,?)");
            
            
            ps.setString(1, uid.getText());
            ps.setString(2, fn.getText());
            ps.setString(3, mn.getText());
            ps.setString(4, ln.getText());
            ps.setString(5, ag.getText());
            
            ps.executeUpdate();

            JOptionPane.showMessageDialog(rootPane, "Saved Successfully");

            uid.setText("");
            fn.setText("");
            mn.setText("");
            ln.setText("");
            ag.setText("");

        } catch (ClassNotFoundException ex) {
            System.getLogger(Sign_in.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        } catch (SQLException ex) {
            System.getLogger(Sign_in.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }
    public void autoincrementid() {
        try {
            d.rs = d.stat.executeQuery("SELECT UserId from student_information ORDER BY UserId DESC LIMIT 1");

            if (d.rs.next()) {
                int id = d.rs.getInt(1);
                int n = id + 1;
                uid.setText(Integer.toString(n));
            }
        } catch (SQLException ex) {
            System.getLogger(Sign_in.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }


