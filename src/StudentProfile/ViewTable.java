    public void showTable(){
        try {                                             // database from SQL
            d.rs = d.stat.executeQuery("SELECT * from student_information");
            while (d.rs.next()){
                String id = d.rs.getString(1);
                String fn = d.rs.getString(2);
                String mn = d.rs.getString(3);
                String ln = d.rs.getString(4);
                String a = d.rs.getString(5);
                
                Object[] content = {id, fn, mn, ln, a};
                
                DefaultTableModel model = (DefaultTableModel) tbl.getModel();
                model.addRow(content);
            }
        
    }   catch (SQLException ex) {
            System.getLogger(ViewTable.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }
